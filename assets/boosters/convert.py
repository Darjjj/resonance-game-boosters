"""Convert approved booster artwork to embedded 48px Windows DIBs.

This is format conversion only: crop sources retain the approved artwork.
Run from any directory; no image dependencies are needed by the plugin.
"""
from pathlib import Path
from PIL import Image, ImageChops, ImageDraw
import struct

ROOT = Path(__file__).resolve().parent
NAMES = ['supercharge', 'encounters0', 'encounters2', 'auto', 'turbo-base']
frames = []
for name in NAMES:
    source = Image.open(ROOT / (name + '-source.png')).convert('RGBA')
    # The overlay uses a black color key. Keep the existing circular rims and
    # remove only the rectangular background outside them before smooth fitting.
    mask = Image.new('L', source.size)
    ImageDraw.Draw(mask).ellipse((1, 1, source.width-2, source.height-2), fill=255)
    source.putalpha(ImageChops.multiply(source.getchannel('A'), mask))
    fitted = source.resize((48, 48), Image.Resampling.LANCZOS)
    opaque = Image.new('RGBA', fitted.size, (0, 0, 0, 255))
    opaque.alpha_composite(fitted)
    frame = opaque.convert('RGB')
    frame.save(ROOT / (name + '.png'))
    pixels = [r << 16 | g << 8 | b for r, g, b in frame.get_flattened_data()]
    (ROOT / (name + '.bgra')).write_bytes(struct.pack('<2304I', *pixels))
    frames.append(pixels)

header = ['#pragma once', '// Generated by assets/boosters/convert.py; do not edit pixels.',
          'namespace booster_art {', 'static constexpr std::uint32_t frames[5][48*48] = {']
for name, pixels in zip(NAMES, frames):
    header.append('    { // ' + name)
    for start in range(0, len(pixels), 16):
        header.append('        ' + ','.join('0x%06x' % p for p in pixels[start:start+16]) + ',')
    header.append('    },')
header.extend(['};', '}'])
(ROOT.parent.parent / 'src' / 'booster_art.hpp').write_text('\n'.join(header)+'\n', encoding='utf-8')

preview = Image.new('RGB', (6*72, 92), '#1b2127')
draw = ImageDraw.Draw(preview)
for i, name in enumerate(NAMES):
    preview.paste(Image.open(ROOT / (name + '.png')), (i*72+12, 6))
    draw.text((i*72+2, 63), name, fill='white')
preview.save(ROOT / 'preview.png')
print('Converted four booster sprites and the shared Turbo background.')
